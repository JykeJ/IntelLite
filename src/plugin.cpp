// IntelLite — SKSE plugin entry point.
//
// At kDataLoaded this DLL resolves the SkyrimNet public API, builds the
// world-wide NPC name index, wires up the MagelightUI panel, and starts the
// task pump.
//
// The vendor headers are reached through the bridge modules, not from here:
//   - skyrimnet_bridge.{h,cpp} is the single TU that includes PublicAPI.h.
//   - panel.{h,cpp} owns the Magelight mod/view and the JS<->C++ bridge.
//   - tasks.{h,cpp} owns the persistent task engine and its pump thread.

#include <REL/Module.h>

#include <string>

#include "movement.h"
#include "panel.h"
#include "skyrimnet_bridge.h"
#include "tasks.h"
#include "actors.h"
#include "npc_index.h"
#include "hotkey.h"

namespace
{
	const char* RuntimeName()
	{
		if (REL::Module::IsVR()) return "VR";
		if (REL::Module::IsAE()) return "AE";
		if (REL::Module::IsSE()) return "SE";
		return "unknown";
	}

	void OnDataLoaded()
	{
		logs::info("IntelLite: kDataLoaded - running startup probes");
		intellite::skyrimnet::Initialize();
		intellite::skyrimnet::RegisterActions();
		intellite::hotkey::Initialize();   // load the stored binding BEFORE the panel binds it
		intellite::panel::Initialize();
		intellite::actors::LoadBlacklist();
		// World-wide NPC index: makes never-met named NPCs searchable/resolvable.
		intellite::npc_index::Build();
		intellite::panel::PushStatus();
		intellite::tasks::Initialize();
		// Movement backend: resolve the travel forms and log availability once.
		const bool movementReady = intellite::movement::IsAvailable();
		const int apiVersion = intellite::skyrimnet::ApiVersion();
		const std::string skyrimnet = apiVersion > 0 ? ("API v" + std::to_string(apiVersion)) : std::string("absent");
		logs::info("IntelLite: runtime {} {} | SkyrimNet {} | Magelight {} | movement {}",
			RuntimeName(),
			REL::Module::get().version().string("."),
			skyrimnet,
			intellite::panel::HostVersion(),
			movementReady ? "package travel" : "simulation");
	}

	void OnMessage(SKSE::MessagingInterface::Message* a_msg)
	{
		if (a_msg->type == SKSE::MessagingInterface::kDataLoaded) {
			OnDataLoaded();
		}
	}
}

// Expands to the exported `SKSEPlugin_Load` (the Version + Query half is
// generated by add_commonlibsse_plugin).
SKSEPluginLoad(const SKSE::LoadInterface* a_skse)
{
	SKSE::Init(a_skse);
	logs::info("IntelLite v{} loaded", "0.1.0");
	intellite::tasks::RegisterSerialization();
	if (auto* msg = SKSE::GetMessagingInterface()) {
		msg->RegisterListener(OnMessage);
	} else {
		logs::error("IntelLite: no messaging interface");
	}
	return true;
}
